"""
Nginx config generation and reload utility.

Writes per-domain server blocks to NGINX_DOMAINS_DIR and reloads nginx
via the Docker Engine API on the mounted unix socket (no docker CLI).
"""
import asyncio
import html
import http.client
import json
import os
import socket
import urllib.parse

NGINX_DOMAINS_DIR = os.getenv("NGINX_DOMAINS_DIR", "/etc/nginx/conf.d/domains")
COMPOSE_PROJECT_NAME = os.getenv("COMPOSE_PROJECT_NAME", "linkspanel")
COMPOSE_SERVICE_NAME = os.getenv("NGINX_COMPOSE_SERVICE", "nginx")

_NGINX_CONTAINER_FALLBACK = f"{COMPOSE_PROJECT_NAME}-nginx-1"

_SERVER_BLOCK_TEMPLATE = """\
# Auto-generated by linkspanel bot — do not edit manually
server {{
    listen 443 ssl http2;
    server_name {domain} *.{domain};

    ssl_certificate     /etc/letsencrypt/live/{domain}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/{domain}/privkey.pem;
    ssl_protocols       TLSv1.2 TLSv1.3;
    ssl_ciphers         HIGH:!aNULL:!MD5;

    location /static/ {{
        alias /app/static/;
        expires 30d;
        add_header Cache-Control "public, immutable";
    }}

    location /chat/stream/ {{
        proxy_pass         http://api:8000;
        proxy_set_header   X-Forwarded-Host $host;
        proxy_set_header   X-Real-IP        $remote_addr;
        proxy_set_header   X-Forwarded-For  $proxy_add_x_forwarded_for;
        proxy_set_header   Host             $host;
        proxy_set_header   Connection       '';
        proxy_http_version 1.1;
        proxy_read_timeout 3600s;
        proxy_buffering    off;
        proxy_cache        off;
        chunked_transfer_encoding on;
    }}

    location / {{
        proxy_pass         http://api:8000;
        proxy_set_header   X-Forwarded-Host $host;
        proxy_set_header   X-Real-IP        $remote_addr;
        proxy_set_header   X-Forwarded-For  $proxy_add_x_forwarded_for;
        proxy_set_header   Host             $host;
        proxy_read_timeout 10s;
    }}
}}
"""


def write_domain_conf(domain: str) -> None:
    """Write an nginx server block for *domain* into NGINX_DOMAINS_DIR."""
    os.makedirs(NGINX_DOMAINS_DIR, exist_ok=True)
    conf_path = os.path.join(NGINX_DOMAINS_DIR, f"{domain}.conf")
    with open(conf_path, "w", encoding="utf-8") as f:
        f.write(_SERVER_BLOCK_TEMPLATE.format(domain=domain))


def remove_domain_conf(domain: str) -> bool:
    """Delete the per-domain nginx conf. Returns True if a file was removed."""
    conf_path = os.path.join(NGINX_DOMAINS_DIR, f"{domain}.conf")
    try:
        os.remove(conf_path)
        return True
    except FileNotFoundError:
        return False


_DOCKER_SOCK = os.getenv("DOCKER_SOCK", "/var/run/docker.sock")


class _UnixHTTPConnection(http.client.HTTPConnection):
    def __init__(self, sock_path: str, timeout: float = 15):
        super().__init__("localhost", timeout=timeout)
        self._sock_path = sock_path

    def connect(self):
        sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        sock.settimeout(self.timeout)
        sock.connect(self._sock_path)
        self.sock = sock


def _docker_request(method: str, path: str, body: dict | None = None, timeout: float = 15) -> tuple[int, bytes]:
    data = json.dumps(body).encode() if body is not None else None
    conn = _UnixHTTPConnection(_DOCKER_SOCK, timeout=timeout)
    try:
        headers = {}
        if data is not None:
            headers["Content-Type"] = "application/json"
            headers["Content-Length"] = str(len(data))
        conn.request(method, path, body=data, headers=headers)
        resp = conn.getresponse()
        raw = resp.read()
        return resp.status, raw
    finally:
        conn.close()


def _find_nginx_container() -> tuple[str | None, str]:
    """Return (container_id_or_name, error). Prefers compose service label."""
    filters = json.dumps({
        "label": [
            f"com.docker.compose.service={COMPOSE_SERVICE_NAME}",
        ],
        "status": ["running"],
    })
    path = "/containers/json?" + urllib.parse.urlencode({"filters": filters})
    status, raw = _docker_request("GET", path)
    if status == 200:
        try:
            containers = json.loads(raw)
        except json.JSONDecodeError:
            containers = None
        if isinstance(containers, list) and containers:
            cid = containers[0].get("Id") or (containers[0].get("Names") or [None])[0]
            if cid:
                return str(cid).lstrip("/"), ""

    # Fallback: default compose name, then common /app project name
    for name in (_NGINX_CONTAINER_FALLBACK, "app-nginx-1", "nginx"):
        st, inspect = _docker_request("GET", f"/containers/{name}/json")
        if st == 200:
            return name, ""
        # keep last error for the user
        last = inspect.decode(errors="replace").strip() or f"HTTP {st}"

    extra = last if "last" in locals() else raw.decode(errors="replace")[:300]
    return None, (
        f"контейнер nginx не найден (искал service={COMPOSE_SERVICE_NAME} "
        f"и {_NGINX_CONTAINER_FALLBACK}). {html.escape(extra)}"
    )


def _reload_nginx_sync() -> tuple[bool, str]:
    if not os.path.exists(_DOCKER_SOCK):
        return False, "Docker-сокет не найден. Проверь volume /var/run/docker.sock в compose."

    container, err = _find_nginx_container()
    if not container:
        return False, err

    status, raw = _docker_request(
        "POST",
        f"/containers/{container}/exec",
        {"AttachStdout": True, "AttachStderr": True, "Cmd": ["nginx", "-s", "reload"]},
    )
    if status not in (200, 201):
        msg = raw.decode(errors="replace").strip() or f"HTTP {status}"
        return False, f"не удалось создать exec в {container}:\n<code>{html.escape(msg)}</code>"

    try:
        exec_id = json.loads(raw).get("Id")
    except json.JSONDecodeError:
        exec_id = None
    if not exec_id:
        return False, f"Docker API не вернул Id exec:\n<code>{html.escape(raw.decode(errors='replace'))}</code>"

    status, raw = _docker_request(
        "POST",
        f"/exec/{exec_id}/start",
        {"Detach": False, "Tty": False},
    )
    output = raw.decode(errors="replace").strip()
    if status not in (200, 201):
        return False, f"nginx reload не запустился:\n<code>{html.escape(str(output or status))}</code>"

    st2, inspect_raw = _docker_request("GET", f"/exec/{exec_id}/json")
    exit_code = None
    if st2 == 200:
        try:
            exit_code = json.loads(inspect_raw).get("ExitCode")
        except json.JSONDecodeError:
            exit_code = None

    if exit_code not in (0, None):
        return False, f"nginx reload завершился с ошибкой:\n<code>{html.escape(str(output or exit_code))}</code>"
    return True, ""


async def reload_nginx() -> tuple[bool, str]:
    """
    Send 'nginx -s reload' inside the nginx container via Docker API.

    Returns (True, "") on success, or (False, error_message) on failure.
    """
    try:
        return await asyncio.wait_for(asyncio.to_thread(_reload_nginx_sync), timeout=20)
    except asyncio.TimeoutError:
        return False, "nginx reload завис (таймаут 20с)."
    except FileNotFoundError:
        return False, "Docker-сокет недоступен."
    except Exception as e:
        return False, f"Ошибка docker exec через сокет: <code>{html.escape(str(e))}</code>"
